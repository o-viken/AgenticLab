test('question, interruption, error and tool-less chat have honest states', async ({ page }) => {
  await open(page)
  await page.getByLabel('Agent', { exact: true }).selectOption('Question')
  await send(page, 'Ask me')
  await expect(page.getByRole('status')).toHaveText('Waiting for you')
  await page.getByRole('textbox', { name: 'Which topic should I use?' }).fill('Tool use')
  await page.getByRole('button', { name: 'Send answer' }).click()
  await expect(page.getByRole('log')).toContainText('You chose: Tool use')
  await page.getByRole('button', { name: 'New conversation' }).click()
  await page.getByLabel('Host', { exact: true }).selectOption('chatgpt')
  await expect(page.getByLabel('Agent', { exact: true })).toHaveValue('Chat')
  await send(page, 'interrupt')
  await expect(page.getByRole('status')).toHaveText('Interrupted')
  await expect(page.getByRole('alert')).toContainText('before a final answer')
  await send(page, 'error')
  await expect(page.getByRole('status')).toHaveText('Failed')
  await expect(page.getByRole('alert')).toContainText('upstream run failed')
  await send(page, 'A normal question')
  await expect(page.getByRole('status')).toHaveText('Complete')
  await expect(page.locator('[data-node="tools"]')).toContainText('No tools')
})

test('keyboard, reduced motion and unavailable catalog are usable', async ({ page }) => {
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await open(page)
  await page.getByRole('button', { name: 'Manual', exact: true }).focus()
  await page.keyboard.press('Space')
  await expect(page.getByRole('button', { name: 'Manual', exact: true })).toHaveAttribute('aria-pressed', 'true')
  const message = page.getByRole('textbox', { name: 'Message', exact: true })
  await message.fill('first line')
  await message.press('Shift+Enter')
  await expect(message).toHaveValue('first line\n')
  await message.press('Enter')
  await expect(page.getByRole('status')).toHaveText('Waiting for Next')
  await page.getByRole('button', { name: 'Stop run' }).click()
  await page.route('**/api/agents', route => route.fulfill({ status: 502, contentType: 'application/problem+json', body: '{"title":"Gateway unavailable"}' }))
  await page.reload()
  await expect(page.getByRole('alert')).toContainText('Gateway unavailable')
  await page.unroute('**/api/agents')
  await page.getByRole('button', { name: 'Retry', exact: true }).click()
  await expect(page.getByLabel('Agent', { exact: true })).toHaveValue('Research')
})